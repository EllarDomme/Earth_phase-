def name_of(lat: float, lon: float) -> str:
    lon = ((lon + 180) % 360) - 180
    best = None
    for la0, la1, lo0, lo1, nm in BOXES:
        if la0 <= lat <= la1 and lo0 <= lon <= lo1:
            # 面积越小越具体
            area = (la1 - la0) * (lo1 - lo0)
            if best is None or area < best[0]:
                best = (area, nm)
    if best:
        return best[1]
    # 兜底：按半球粗略命名
    ns = "北" if lat >= 0 else "南"
    ew = "东" if lon >= 0 else "西"
    return "%s纬%.0f° %s经%.0f°" % (ns, abs(lat), ew, abs(lon))


def describe_region(lat_range, lon_range) -> str:
    """给一个经纬范围起名：采样 3×3 网格，去重后用"—"连起来"""
    la0, la1 = sorted(lat_range)
    lo0, lo1 = sorted(lon_range)
    from collections import Counter, defaultdict
    cnt = Counter(); lats = defaultdict(list)
    for i in range(5):
        for j in range(5):
            la = la0 + (la1 - la0) * i / 4
            lo = lo0 + (lo1 - lo0) * j / 4
            nm = name_of(la, lo)
            cnt[nm] += 1; lats[nm].append(la)
    top = [k for k, _ in sorted(cnt.items(), key=lambda kv: -kv[1])[:3]]
    top.sort(key=lambda k: -sum(lats[k]) / len(lats[k]))     # 北 → 南
    return "—".join(top)


